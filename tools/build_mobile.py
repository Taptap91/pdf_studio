#!/usr/bin/env python3
"""Builds mobile/engine.js from the tagging code inside pdf_studio.py.

The desktop app's page keeps its tagging engine (autoTagFile and everything it calls) in one script. This pulls
just that engine out, so the phone page runs the same tagging with no local server. Run it again after any change
to pdf_studio.py:  python3 tools/build_mobile.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "pdf_studio.py").read_text(encoding="utf-8")
page = re.search(r'PAGE = r"""(.*?)"""', src, re.S).group(1)
script = re.findall(r"<script[^>]*>(.*?)</script>", page, re.S)[-1]


REGEX_AFTER = set("(,=:[!&|?{};+-*%<>~^")

def skip_regex(s, i):
    """i is at a '/' that starts a regex literal; returns the index just past it (and its flags)."""
    i += 1; in_class = False
    while i < len(s):
        c = s[i]
        if c == "\\": i += 2; continue
        if c == "[": in_class = True
        elif c == "]": in_class = False
        elif c == "/" and not in_class: i += 1; break
        elif c == "\n": break
        i += 1
    while i < len(s) and s[i].isalpha(): i += 1
    return i

def is_regex_start(s, i):
    j = i - 1
    while j >= 0 and s[j] in " \t": j -= 1
    return j < 0 or s[j] in REGEX_AFTER or s[max(0, j - 5):j + 1].endswith("return")

def skip_string(s, i):
    """i is at an opening quote; returns the index just past the closing quote."""
    q = s[i]; i += 1
    while i < len(s):
        c = s[i]
        if c == "\\": i += 2; continue
        if q == "`" and c == "$" and i + 1 < len(s) and s[i + 1] == "{":
            i = match_brace(s, i + 1) + 1; continue
        if c == q: return i + 1
        i += 1
    return i

def match_brace(s, i):
    """i is at '{'; returns the index of its matching '}'."""
    depth = 0
    while i < len(s):
        c = s[i]
        if c in "\"'`": i = skip_string(s, i); continue
        if s.startswith("//", i): i = s.index("\n", i); continue
        if s.startswith("/*", i): i = s.index("*/", i) + 2; continue
        if c == "/" and is_regex_start(s, i): i = skip_regex(s, i); continue
        if c == "{": depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0: return i
        i += 1
    raise ValueError("unbalanced")

def block_end(s, start):
    """End (exclusive) of a top-level function or declaration starting at `start`."""
    i = start; depth = 0
    while i < len(s):
        c = s[i]
        if c in "\"'`": i = skip_string(s, i); continue
        if s.startswith("//", i): i = s.index("\n", i); continue
        if s.startswith("/*", i): i = s.index("*/", i) + 2; continue
        if c == "/" and is_regex_start(s, i): i = skip_regex(s, i); continue
        if c in "([{": depth += 1
        elif c in ")]}": depth -= 1
        elif c == ";" and depth == 0: return i + 1
        elif c == "}" and depth == 0: return i + 1
        i += 1
    return i

def top_level(name):
    """(start, end) of a top-level function or const/let/var named `name`, or None."""
    m = re.search(rf"^(?:async )?function {name}\b|^(?:const|let|var) {name}\b", script, re.M)
    if not m: return None
    start = m.start()
    if script.startswith("function", start) or script.startswith("async function", start):
        brace = script.index("{", m.end())
        return start, match_brace(script, brace) + 1
    return start, block_end(script, start)

NEEDED = ["autoTagFile"]
seen, order = set(), []
while NEEDED:
    name = NEEDED.pop()
    if name in seen: continue
    seen.add(name)
    span = top_level(name)
    if not span: continue
    order.append((name, span))
    body = script[span[0]:span[1]]
    for ident in set(re.findall(r"(?<![.\w$])([A-Za-z_$][\w$]*)\b", body)):
        if ident not in seen and top_level(ident):
            NEEDED.append(ident)

order.sort(key=lambda x: x[1][0])
parts = [script[a:b] for _, (a, b) in order]
engine = "/* Generated by tools/build_mobile.py from pdf_studio.py. Do not edit by hand. */\n"
engine += "\n".join(parts) + "\n"
# the pdf.js files sit beside the page on the phone, not at the desktop server's /vendor path
engine = engine.replace('import("/vendor/pdf.mjs")', 'import("./vendor/pdf.mjs")').replace('"/vendor/pdf.worker.mjs"', '"./vendor/pdf.worker.mjs"')
out = ROOT / "mobile" / "engine.js"
out.parent.mkdir(exist_ok=True)
out.write_text(engine, encoding="utf-8")
print("engine.js:", len(engine), "bytes,", len(order), "declarations:", ", ".join(n for n, _ in order))
